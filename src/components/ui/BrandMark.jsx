// Real brand marks for the OAuth buttons.
//
// Kept apart from Icon.jsx deliberately. That file maps semantic names onto
// lucide glyphs — `tiktok: Music2` is a music note standing in for a logo,
// which is fine for a niche chip and not fine on a sign-in button. Google's
// brand guidelines require their actual mark on a "Sign in with Google"
// control, and a button offering someone's identity provider should look
// like that provider.
//
// Inline SVG rather than image files: three small paths, no network request,
// and they inherit sizing from the call site.

