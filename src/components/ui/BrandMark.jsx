// One place that maps a provider id to its mark, so a screen offering these
// logins does not keep its own copy of the mapping. Auth.jsx had the only
// one, which meant anywhere else showing the same providers had to repeat it
// and could fall out of step when one was added.
export function ProviderMark({ provider, size }) {
  switch (provider) {
    case 'google':   return <GoogleMark   {...(size ? { size } : {})} />
    case 'facebook': return <FacebookMark {...(size ? { size } : {})} />
    case 'twitter':  return <XMark        {...(size ? { size } : {})} />
    default:         return null
  }
}
